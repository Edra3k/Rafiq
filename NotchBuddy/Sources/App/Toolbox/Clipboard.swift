// MARK: - Clipboard history
//
// While the feature is on, Rafiq looks at the clipboard's change count twice a second and keeps
// what was copied (text, links, files, small images) on this Mac. Password managers' items
// (marked concealed or transient) are never kept; a key or token is masked, kept in memory only,
// and wiped from the clipboard after 30 s. Links lose their tracking parameters when Clean URL
// is on. Pinned items stay; the rest keeps the last 200.

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, link, file, image, secret }
    var id = UUID()
    var kind: Kind
    var text: String
    var paths: [String] = []
    var date = Date()
    var pinned = false
    var app: String?
    var cleaned = false
    /// In memory only (images and secrets are never written to disk).
    var imageData: Data? = nil

    enum CodingKeys: String, CodingKey { case id, kind, text, paths, date, pinned, app, cleaned }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let autoClearKey = "clipboard.autoClearMinutes"

    @Published private(set) var items: [ClipItem] = []
    @Published var query = ""

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var ownWrite = -1
    private var clearWork: DispatchWorkItem?

    private static var file: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchBuddy", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("clipboard.json")
    }

    private init() {
        if let data = try? Data(contentsOf: Self.file), let saved = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = saved
        }
    }

    /// Called at launch and when the feature changes.
    func featureChanged() {
        if FeatureHub.shared.isOn(.clipboard) {
            guard timer == nil else { return }
            lastCount = NSPasteboard.general.changeCount
            timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
                Task { @MainActor in self?.poll() }
            }
        } else {
            timer?.invalidate()
            timer = nil
        }
    }

    var shown: [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces).lowercased()
        let list = q.isEmpty ? items : items.filter { $0.text.lowercased().contains(q) }
        return list.filter(\.pinned) + list.filter { !$0.pinned }
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        guard board.changeCount != ownWrite else { return }
        let types = board.types ?? []
        let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                 "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
        if types.contains(where: { skip.contains($0.rawValue) }) { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName

        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            add(ClipItem(kind: .file, text: urls.map(\.lastPathComponent).joined(separator: ", "), paths: urls.map(\.path), app: app))
        } else if let text = board.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            if !SecretScanner.scan(text).isEmpty {
                let shown = text.hasPrefix("-----BEGIN") ? "-----BEGIN ••••••••" : SecretScanner.mask(String(text.prefix(60)))
                add(ClipItem(kind: .secret, text: shown, app: app), persist: false)
                wipe(after: 30)
                return
            }
            var value = text
            var cleaned = false
            if FeatureHub.shared.isOn(.cleanURL), let clean = URLCleaner.clean(text), clean != text {
                value = clean
                cleaned = true
                write(clean)
            }
            let isLink = URL(string: value.trimmingCharacters(in: .whitespacesAndNewlines))?.scheme?.hasPrefix("http") == true
            add(ClipItem(kind: isLink ? .link : .text, text: value, app: app, cleaned: cleaned))
        } else if let image = NSImage(pasteboard: board), let tiff = image.tiffRepresentation,
                  let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]), png.count < 8_000_000 {
            var item = ClipItem(kind: .image, text: "\(Int(image.size.width))×\(Int(image.size.height))", app: app)
            item.imageData = png
            add(item)
        }
        if let minutes = UserDefaults.standard.object(forKey: Self.autoClearKey) as? Double, minutes > 0 { wipe(after: minutes * 60) }
    }

    private func add(_ item: ClipItem, persist: Bool = true) {
        _ = persist
        if let same = items.firstIndex(where: { $0.kind == item.kind && $0.text == item.text && $0.paths == item.paths }) {
            var existing = items.remove(at: same)
            existing.date = Date()
            items.insert(existing, at: 0)
        } else {
            items.insert(item, at: 0)
        }
        var unpinned = 0
        items = items.filter { $0.pinned || { unpinned += 1; return unpinned <= 200 }() }
        save()
    }

    /// Clears the system clipboard after a delay, unless something else was copied meanwhile.
    private func wipe(after seconds: TimeInterval) {
        clearWork?.cancel()
        let count = NSPasteboard.general.changeCount
        let work = DispatchWorkItem {
            MainActor.assumeIsolated {
                guard NSPasteboard.general.changeCount == count else { return }
                NSPasteboard.general.clearContents()
                ClipboardHistory.shared.items.removeAll { $0.kind == .secret }
            }
        }
        clearWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + seconds, execute: work)
    }

    func write(_ text: String) {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        ownWrite = board.changeCount
        lastCount = board.changeCount
    }

    /// Puts the item back on the clipboard (and pastes it in the front app when asked).
    func use(_ item: ClipItem, paste: Bool) {
        let board = NSPasteboard.general
        switch item.kind {
        case .secret: return
        case .file:
            board.clearContents()
            board.writeObjects(item.paths.map { URL(fileURLWithPath: $0) as NSURL })
            ownWrite = board.changeCount
        case .image:
            board.clearContents()
            if let data = item.imageData { board.setData(data, forType: .png) }
            ownWrite = board.changeCount
        case .text, .link:
            if paste { _ = FlowPaste.insert(item.text); return }
            write(item.text)
        }
        lastCount = board.changeCount
        if paste { Self.sendPaste() }
    }

    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(of: item) else { return }
        items[i].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clearUnpinned() {
        items.removeAll { !$0.pinned }
        save()
    }

    private func save() {
        let kept = items.filter { $0.kind != .secret && $0.kind != .image }
        if let data = try? JSONEncoder().encode(kept) { try? data.write(to: Self.file, options: [.atomic]) }
    }

    /// The text of the clipboard pasted without its formatting (⌃⌥⇧V).
    static func pastePlain() {
        guard let text = NSPasteboard.general.string(forType: .string) else { return }
        _ = FlowPaste.insert(text)
    }

    static func sendPaste() {
        guard AXIsProcessTrusted() else { return }
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = FlowPaste.vKeyCode()
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

// MARK: - Clean URL

enum URLCleaner {
    static let tracking: Set<String> = [
        "fbclid", "gclid", "gclsrc", "dclid", "msclkid", "mc_cid", "mc_eid", "igshid", "igsh", "yclid", "_hsenc", "_hsmi",
        "mkt_tok", "oly_anon_id", "oly_enc_id", "vero_id", "wickedid", "ref_src", "ref_url", "s_cid", "twclid", "ttclid",
        "srsltid", "si", "feature", "pp", "spm", "scm", "trk", "trkCampaign", "sc_campaign", "zanpid", "rb_clickid", "epik",
    ]

    /// The link without its tracking parameters; nil when the text isn't one link.
    static func clean(_ text: String) -> String? {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.contains(" "), !trimmed.contains("\n"),
              var parts = URLComponents(string: trimmed), let scheme = parts.scheme, scheme.hasPrefix("http"),
              let items = parts.queryItems, !items.isEmpty else { return nil }
        let host = parts.host ?? ""
        let kept = items.filter { item in
            let name = item.name.lowercased()
            if name.hasPrefix("utm_") || tracking.contains(name) {
                // YouTube's own "feature" or "si" are tracking; elsewhere "si"/"feature"/"pp" may be real.
                if ["si", "feature", "pp"].contains(name) { return !(host.contains("youtu") || host.contains("spotify")) }
                return false
            }
            return true
        }
        guard kept.count != items.count else { return trimmed }
        parts.queryItems = kept.isEmpty ? nil : kept
        return parts.string
    }
}

// MARK: - Shelf: files parked in the island

@MainActor
final class Shelf: ObservableObject {
    static let shared = Shelf()
    @Published private(set) var paths: [String] = []
    private let key = "shelf.paths"

    private init() {
        paths = (UserDefaults.standard.stringArray(forKey: key) ?? []).filter { FileManager.default.fileExists(atPath: $0) }
    }

    func add(_ urls: [URL]) {
        for url in urls where !paths.contains(url.path) { paths.insert(url.path, at: 0) }
        UserDefaults.standard.set(paths, forKey: key)
    }

    func remove(_ path: String) {
        paths.removeAll { $0 == path }
        UserDefaults.standard.set(paths, forKey: key)
    }

    func clear() {
        paths = []
        UserDefaults.standard.set(paths, forKey: key)
    }
}

// MARK: - Scratchpad

struct ScratchNote: Identifiable, Codable, Equatable {
    var id = UUID()
    var title: String
    var text: String
}

@MainActor
final class Scratchpad: ObservableObject {
    static let shared = Scratchpad()
    @Published var notes: [ScratchNote] = [] { didSet { scheduleSave() } }
    @Published var selected: UUID?
    private var saveWork: DispatchWorkItem?

    private static var file: URL {
        let dir = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("NotchBuddy", isDirectory: true)
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
        return dir.appendingPathComponent("scratchpad.json")
    }

    private init() {
        if let data = try? Data(contentsOf: Self.file), let saved = try? JSONDecoder().decode([ScratchNote].self, from: data), !saved.isEmpty {
            notes = saved
        } else {
            notes = [ScratchNote(title: String(localized: "notes.first", defaultValue: "Notes"), text: "")]
        }
        selected = notes.first?.id
    }

    func binding(for id: UUID) -> Binding<String> {
        Binding(get: { self.notes.first { $0.id == id }?.text ?? "" },
                set: { value in if let i = self.notes.firstIndex(where: { $0.id == id }) { self.notes[i].text = value } })
    }

    func add() {
        let note = ScratchNote(title: String(format: String(localized: "notes.new %lld", defaultValue: "Note %lld"), notes.count + 1), text: "")
        notes.append(note)
        selected = note.id
    }

    func delete(_ id: UUID) {
        notes.removeAll { $0.id == id }
        if notes.isEmpty { notes = [ScratchNote(title: String(localized: "notes.first", defaultValue: "Notes"), text: "")] }
        selected = notes.first?.id
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let snapshot = notes
        let work = DispatchWorkItem {
            if let data = try? JSONEncoder().encode(snapshot) { try? data.write(to: Scratchpad.file, options: [.atomic]) }
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8, execute: work)
    }
}
